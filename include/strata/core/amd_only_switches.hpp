/// Non-HIP builds: clear every AMD-only switch that is set, with one line naming them.  Call first thing in main().
inline void clear_amd_only_switches() {
#if !defined(STRATA_USE_HIP)
    int n = 0;
    for (const char* name : kAmdOnlySwitches) {
        if (std::getenv(name) == nullptr) continue;
        std::fprintf(stderr, "%s%s", n == 0 ? "speedy: RX 7900 XTX (HIP) only, ignored on this build: " : " ", name);
#if defined(_WIN32)
        _putenv_s(name, "");
#else
        unsetenv(name);
#endif
        ++n;
    }
    if (n > 0) std::fprintf(stderr, "\n");
#endif
}

